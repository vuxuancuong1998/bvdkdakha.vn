CREATE TABLE IF NOT EXISTS hicrm_equipment (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT,
 name VARCHAR(255) NOT NULL,
 manufacturer VARCHAR(120) NOT NULL DEFAULT '',
 origin VARCHAR(120) NOT NULL DEFAULT '',
 description TEXT NOT NULL,
 image_path VARCHAR(500) NOT NULL,
 sort_order INT NOT NULL DEFAULT 0,
 status TINYINT NOT NULL DEFAULT 1,
 sample_code VARCHAR(50) DEFAULT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY (id),
 UNIQUE KEY uniq_sample_code (sample_code),
 KEY idx_equipment_display (status, sort_order, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
